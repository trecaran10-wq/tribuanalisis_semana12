import sqlite3
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    company TEXT NOT NULL DEFAULT '',
    period TEXT NOT NULL DEFAULT '',
    imported INTEGER NOT NULL DEFAULT 0,
    display_name TEXT,
    registered_at TEXT,
    last_login TEXT
);
CREATE TABLE IF NOT EXISTS cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    support TEXT NOT NULL,
    expense BIGINT NOT NULL,
    deductible BIGINT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT
);
CREATE TABLE IF NOT EXISTS drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    category TEXT NOT NULL,
    fields TEXT NOT NULL,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS draft_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL REFERENCES drafts(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content BYTEA NOT NULL
);
CREATE TABLE IF NOT EXISTS draft_reviews (
    draft_id BIGINT PRIMARY KEY REFERENCES drafts(id) ON DELETE CASCADE,
    data TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS case_drafts (
    draft_id BIGINT PRIMARY KEY REFERENCES drafts(id) ON DELETE CASCADE,
    case_id BIGINT NOT NULL UNIQUE REFERENCES cases(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS report_settings (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    data TEXT NOT NULL
);
"""

UPLOAD_SCHEMA = """
CREATE TABLE IF NOT EXISTS upload_batches (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    token TEXT NOT NULL UNIQUE,
    files TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS upload_chunks (
    token TEXT NOT NULL REFERENCES upload_batches(token) ON DELETE CASCADE,
    file_index INTEGER NOT NULL,
    chunk_index INTEGER NOT NULL,
    content BINARY_TYPE NOT NULL,
    PRIMARY KEY (token, file_index, chunk_index)
);
"""


class PostgresConnection:
    def __init__(self, url):
        self.connection = psycopg.connect(url, row_factory=dict_row)

    def execute(self, query, parameters=()):
        query = query.replace("CURRENT_TIMESTAMP", "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")
        return self.connection.execute(query.replace("?", "%s"), parameters)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def connect(database, database_url):
    if database_url:
        return PostgresConnection(database_url)
    connection = sqlite3.connect(database)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


def initialize_postgres(connection):
    connection.execute("SELECT pg_advisory_xact_lock(72425612)")
    for statement in POSTGRES_SCHEMA.split(";"):
        if statement.strip():
            connection.execute(statement)
    initialize_uploads(connection, True)
    connection.commit()


def initialize_uploads(connection, postgres):
    sql = UPLOAD_SCHEMA.replace("BINARY_TYPE", "BYTEA" if postgres else "BLOB")
    for statement in sql.split(";"):
        if statement.strip():
            connection.execute(statement)


def lock_user(connection, user_id, postgres):
    if postgres:
        connection.execute("SELECT id FROM users WHERE id = ? FOR UPDATE", (user_id,)).fetchone()
    else:
        connection.execute("BEGIN IMMEDIATE")


@contextmanager
def atomic(connection):
    try:
        yield
    except Exception:
        connection.rollback()
        raise
    else:
        connection.commit()
